    static var metadataNotes: [String: Any] { [
        "intelligence_note": "Quota utilization describes the whole account. Local tokens describe only the activity this Mac observed, so a change in utilization is not attributed to local tokens except in the efficiency columns, which are labelled observed associations.",
        "projection_note": "Cycles with boundary_origin projected come from an established reset schedule. They never carry utilization readings, and no utilization is ever inferred for them.",
        "forecast_note": "A forecast is a prediction from the history of reported utilization, not a provider limit. Its range comes from the method's past errors and is empty when there is not enough history.",
    ] }

    private static let index: [String: Int] = Dictionary(uniqueKeysWithValues: columns.enumerated().map { ($1.name, $0) })

    private static func iso(_ date: Date?, zone: TimeZone? = nil) -> Cell {
        guard let date else { return .null }
        guard let zone else { return .text(ExportService.iso(date)) }
        let formatter = ISO8601DateFormatter()
        formatter.timeZone = zone
        formatter.formatOptions = [.withInternetDateTime]
        return .text(formatter.string(from: date))
    }

    private static func real(_ value: Double?) -> Cell { value.map { .real($0) } ?? .null }

    static func rows(report: SubscriptionUsageReport, forecast: UsageForecast, zone: TimeZone) -> [[Cell]] {
        let subject = report.subject
        var out: [[Cell]] = []

        func base(_ type: String, plan: CyclePlan?) -> [String: Cell] {
            let planText: String = {
                guard let plan else { return "" }
                return plan.changedDuringCycle ? "mixed:" + (plan.key ?? "") : (plan.key ?? "")
            }()
            return ["row_type": .text(type), "provider": .text(subject.provider.rawValue), "account": .text(subject.accountLabel),
                    "plan": .text(planText), "pool": .text(subject.poolKey), "window": .text(subject.windowKey),
                    "window_minutes": subject.windowMinutes.map { .int(Int64($0)) } ?? .null,
                    "scope": subject.scopeLabel.map { .text($0) } ?? .null]
        }

        func local(_ summary: LocalUsageSummary) -> [String: Cell] {
            let t = summary.tokens
            return ["requests": .int(Int64(summary.requests)), "sessions": .int(Int64(summary.sessions)),
                    "subagent_sessions": .int(Int64(summary.subagentSessions)), "processed_tokens": .int(t.totalProcessed),
                    "fresh_tokens": .int(t.freshTokens), "uncached_input_tokens": .int(t.uncachedInput),
                    "output_tokens": .int(t.output), "cache_read_tokens": .int(t.cacheRead),
                    "cache_creation_tokens": .int(t.cacheCreation), "cache_creation_5m_tokens": .int(t.cacheCreation5m),
                    "cache_creation_1h_tokens": .int(t.cacheCreation1h), "cache_read_share": real(t.cacheHitRatio),
                    "estimated_cost_pico_usd": .int(summary.cost.picoUSD), "active_hours": .real(summary.activeDuration / 3600)]
        }

        func place(_ cells: [String: Cell]) -> [Cell] {
            var row = [Cell](repeating: .null, count: columns.count)
            for (name, cell) in cells { if let i = index[name] { row[i] = cell } }
            return row
        }

        for cycle in report.cycles {
            var cells = base("cycle", plan: cycle.plan)
            cells.merge(local(cycle.local)) { _, new in new }
            cells["period_start"] = iso(cycle.span.start)
            cells["period_end"] = iso(cycle.span.end)
            cells["period_start_local"] = iso(cycle.span.start, zone: zone)
            cells["boundary_origin"] = .text(cycle.span.origin.rawValue)
            cells["ended_early"] = .text(cycle.span.endedEarly ? "true" : "false")
            cells["expected_reset"] = iso(cycle.expectedReset)
            cells["local_attribution"] = .text(cycle.attribution.rawValue)
            cells["local_attributed_share"] = real(cycle.attributedShare)
            cells["local_unattributed_tokens"] = .int(cycle.unattributed.processedTokens)
            if let q = cycle.quota {
                cells["quota_readings"] = .int(Int64(q.readingCount))
                cells["quota_first_percent"] = real(q.firstPercent)
                cells["quota_last_percent"] = real(q.lastPercent)
                cells["quota_max_percent"] = real(q.maximumPercent)
                cells["quota_observed_rise_points"] = real(q.observedRisePoints)
                cells["quota_start_observed"] = .text(q.startObserved ? "true" : "false")
                cells["quota_end_observed"] = .text(q.endObserved ? "true" : "false")
                cells["quota_reached_limit"] = .text(q.reachedLimit ? "true" : "false")
                cells["quota_final_percent"] = real(q.finalPercent)
                let coverage = q.coverage
                cells["quota_first_observation_delay_hours"] = real(coverage.firstObservationDelay.map { $0 / 3600 })
                cells["quota_last_observation_lead_hours"] = real(coverage.lastObservationLead.map { $0 / 3600 })
                cells["quota_observation_count"] = coverage.observationCount.map { .int(Int64($0)) } ?? .null
                cells["quota_largest_unresolved_gap_hours"] = .real(coverage.largestUnresolvedGap / 3600)
                cells["quota_longest_unchanged_hours"] = .real(coverage.longestUnchangedStretch / 3600)
                cells["quota_determined_fraction"] = .real(coverage.determinedFraction)
                cells["quota_supported_fraction"] = .real(coverage.supportedFraction)
                cells["quota_reliable_full_cycle"] = .text(coverage.hasReliableFullCycleResult ? "true" : "false")
                cells["quota_completeness"] = .text(q.completeness.rawValue)
                cells["quota_sources"] = .text(q.sources.joined(separator: ";"))
            } else {
                cells["quota_completeness"] = .text(CycleCompleteness.unobserved.rawValue)
            }
            let e = cycle.efficiency
            cells["efficiency_quality"] = e.quality.map { .text($0.rawValue) } ?? .null
            cells["efficiency_unavailable_reasons"] = .text(e.unavailable.map(\.rawValue).joined(separator: ";"))
            cells["efficiency_caveats"] = .text(e.caveats.map(\.rawValue).joined(separator: ";"))
            if e.isAvailable {
                cells["efficiency_rise_points"] = .real(e.risePoints)
                cells["efficiency_processed_tokens_per_point"] = real(e.processedTokensPerPoint?.value)
                cells["efficiency_processed_tokens_per_point_low"] = real(e.processedTokensPerPoint?.low)
                cells["efficiency_processed_tokens_per_point_high"] = real(e.processedTokensPerPoint?.high)
                cells["efficiency_fresh_tokens_per_point"] = real(e.freshTokensPerPoint?.value)
                cells["efficiency_cost_usd_per_point"] = real(e.costUSDPerPoint?.value)
                cells["efficiency_points_per_million_processed"] = real(e.pointsPerMillionProcessed?.value)
            }
            out.append(place(cells))

            for day in cycle.days {
                var dayCells = base("day", plan: cycle.plan)
                dayCells.merge(local(day.local)) { _, new in new }
                dayCells["period_start"] = iso(day.start)
                dayCells["period_end"] = iso(day.end)
                dayCells["period_start_local"] = iso(day.start, zone: zone)
                dayCells["boundary_origin"] = .text(cycle.span.origin.rawValue)
                dayCells["day_index"] = .int(Int64(day.index))
                dayCells["local_attribution"] = .text(cycle.attribution.rawValue)
                switch day.quotaChange {
                case .exact(let value):
                    dayCells["quota_change_lower"] = .real(value)
                    dayCells["quota_change_upper"] = .real(value)
                case .between(let low, let high):
                    dayCells["quota_change_lower"] = .real(low)
                    dayCells["quota_change_upper"] = .real(high)
                case .unavailable:
                    dayCells["note"] = .text("quota change unavailable: the day lies outside the observed part of the cycle")
                }
                out.append(place(dayCells))
            }
        }

        var cells = base("forecast", plan: report.currentCycle?.plan)
        switch forecast.availability {
        case .forecast: cells["forecast_status"] = .text("forecast")
        case .limitReached: cells["forecast_status"] = .text("limitReached")
        case .unavailable(let reasons):
            cells["forecast_status"] = .text("unavailable")
            cells["note"] = .text(reasons.map(describe).joined(separator: "; "))
        }
        cells["forecast_method"] = forecast.method.map { .text($0.rawValue) } ?? .null
        cells["forecast_as_of"] = iso(forecast.asOf)
        cells["forecast_current_percent"] = real(forecast.currentPercent)
        cells["forecast_low_percent"] = real(forecast.low)
        cells["forecast_point_percent"] = real(forecast.point)
        cells["forecast_high_percent"] = real(forecast.high)
        cells["forecast_exhaustion_earliest"] = iso(forecast.exhaustion?.earliest)
        cells["forecast_exhaustion_latest"] = iso(forecast.exhaustion?.latest)
        cells["forecast_held_out_cases"] = .int(Int64(forecast.evidence.heldOutCases))
        cells["forecast_mean_abs_error"] = real(forecast.evidence.meanAbsoluteError)
        cells["forecast_no_growth_error"] = real(forecast.evidence.noGrowthMeanAbsoluteError)
        cells["forecast_bias"] = real(forecast.evidence.bias)
        out.append(place(cells))
        return out
    }

    private static func describe(_ reason: ForecastUnavailableReason) -> String {
        switch reason {
        case .noCurrentCycle: "no current cycle"
        case .noReadings: "no readings in the current cycle"
        case .tooFewReadings: "fewer than two distinct readings"
        case .readingsStale: "the last reading is too old"
        case .cycleEnded: "the cycle has ended"
        case .notEnoughCompletedCycles(let have, let need): "\(have) of \(need) completed cycles needed"
        case .planChangedDuringCycle: "the plan changed during the cycle"
        case .errorTooLarge: "held-out forecast errors are too large"
        case .noBetterThanNoGrowth: "held-out forecasts are no better than assuming no further use"
        }
    }
}
